# In this chapter we are going to learn the variable. Lets start: 
# Whar is a variable? A variable is a container that holds a value. In python, variables are used to store data that can be used later in the program. Variables can hold different types of data, such as numbers, strings, lists, and more.
# In python, you can create a variable by assigning a value to it using the assignment operator (=). The variable name should be descriptive and follow the naming conventions of python. Variable names can contain letters, numbers, and underscores, but they cannot start with a number or contain spaces. It is also important to note that variable names are case-sensitive, which means that "myVariable" and "myvariable" are considered different variables.
