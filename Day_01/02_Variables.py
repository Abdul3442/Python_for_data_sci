#Types of variables in python: There are several types of variables in python, including:
# 1. Integer: A variable that holds a whole number (e.g., x = 5)
# 2. Float: A variable that holds a decimal number (e.g., y = 3.14)
# 3. String: A variable that holds a sequence of characters (e.g., name = "John")
# 4. Boolean: A variable that holds a True or False value (e.g., is_valid = True)
# 5. List: A variable that holds a collection of values (e.g., numbers = [1, 2, 3, 4, 5])
# 6. Tuple: A variable that holds a collection of values that cannot be changed (e.g., coordinates = (10, 20))

