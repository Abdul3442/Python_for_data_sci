## String is a data type in python that is used to represent text. It is a sequence of characters enclosed in either single quotes (' ') or double quotes (" "). Strings can contain letters, numbers, symbols, and whitespace. In python, strings are immutable, which means that once they are created, they cannot be changed. However, you can create new strings by concatenating or slicing existing strings.

print("Hello World") # This line of code will print the message "Hello World" to the console.
print ("This is my first python program") # This line of code will print the message "This is my first python program" to the console.
print ("I am excited to learn python for data science") # This line of code will print the message "I am excited to learn python for data science" to the console.

#Single quates and double quotes can be used interchangeably to define strings in python. However, it is a good practice to be consistent with the use of quotes throughout your code. If you start a string with a single quote, you should end it with a single quote, and if you start a string with a double quote, you should end it with a double quote. This helps to avoid syntax errors and makes your code more readable.
print ('This is a string defined using single quotes') #This line of code will print the message "This is a string defined using single quotes" to the console.
print ("This is a string defined using double quotes") # This line of code will print the message "This is a string defined using double quotes" to the console.

# Arithmetic operations in python are used to perform mathematical calculations. The basic arithmetic operations in python are addition (+), subtraction (-), multiplication (*), division (/), modulus (%), exponentiation (**), and floor division (//). These operations can be performed on numbers (integers and floats) and can also be combined with variables to create more complex expressions.
print (5 + 3) # This line of code will print the result of the addition operation (5 + 3) to the console.
print (10 - 4) # This line of code will print the result of the subtraction operation (10 - 4) to the console.
print (6 * 7) # This line of code will print the result of the multiplication operation (6 * 7) to the console.
print (20 / 4) # This line of code will print the result of the division operation (20 / 4) to the console.
print (15 % 4) # This line of code will print the result of the modulus operation (15 % 4) to the console.
print (2 ** 3) # This line of code will print the result of the exponentiation operation (2 ** 3) to the console.
print (15 // 4) # This line of code will print the result of the floor division operation (15 // 4) to the console.
#This line follows the order of operations (PEMDAS) to calculate the result. First, the multiplication and division are performed from left to right, then the addition and subtraction are performed from left to right.
print(2*5/10+20-20) # This line of code will print the result of the complex arithmetic operation (2*5/10+20-20) to the console.

