# How to find the type of variable in python? You can use the built-in type() function to find the type of a variable in python. The type() function takes a variable as an argument and returns its data type. Here is an example:
x=5
print (type(x)) # This line of code will print the data type of the variable x to the console, which is <class 'int'>.
y=3.14
print (type(y)) # This line of code will print the data type of the variable y to the console, which is <class 'float'>.


